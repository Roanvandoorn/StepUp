function animateProductToCart(){
  if(matchMedia('(prefers-reduced-motion: reduce)').matches)return Promise.resolve();
  const source=document.getElementById('detailMainImage');
  const target=document.getElementById('cartDrawerBtn');
  if(!source||!target)return Promise.resolve();
  const a=source.getBoundingClientRect(),b=target.getBoundingClientRect();
  if(a.width<5||a.height<5)return Promise.resolve();

  const clone=source.cloneNode();
  clone.removeAttribute('id');
  clone.className='fly-to-cart';
  Object.assign(clone.style,{
    left:`${a.left}px`,top:`${a.top}px`,width:`${a.width}px`,height:`${a.height}px`
  });
  document.body.appendChild(clone);

  const tx=(b.left+b.width/2)-(a.left+a.width/2);
  const ty=(b.top+b.height/2)-(a.top+a.height/2);
  const targetScale=Math.max(.04,Math.min(.14,b.width/a.width));

  const animation=clone.animate([
    {transform:'translate3d(0,0,0) scale(1) rotate(0deg)',opacity:1,filter:'blur(0)'},
    {offset:.62,transform:`translate3d(${tx*.72}px,${ty*.72}px,0) scale(.28) rotate(-5deg)`,opacity:.94,filter:'blur(0)'},
    {transform:`translate3d(${tx}px,${ty}px,0) scale(${targetScale}) rotate(4deg)`,opacity:.08,filter:'blur(2px)'}
  ],{duration:580,easing:'cubic-bezier(.16,.8,.2,1)',fill:'forwards'});

  return animation.finished.catch(()=>{}).finally(()=>{
    clone.remove();
    target.classList.remove('cart-arrival');
    void target.offsetWidth;
    target.classList.add('cart-arrival');
    const count=target.querySelector('.cart-count');
    if(count){
      count.classList.remove('count-pop');
      void count.offsetWidth;
      count.classList.add('count-pop');
    }
    setTimeout(()=>target.classList.remove('cart-arrival'),700);
  });
}

